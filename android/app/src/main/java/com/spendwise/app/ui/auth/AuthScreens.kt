/** Stateless: easy to preview and to UI-test without Hilt or Firebase. */
@Composable
fun AuthForm(
    isRegister: Boolean,
    state: AuthUiState,
    onEmail: (String) -> Unit,
    onPassword: (String) -> Unit,
    onSubmit: () -> Unit,
    onGoogle: () -> Unit,
    onSwitch: () -> Unit,
) {
    Column(
        Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(24.dp),
        verticalArrangement = Arrangement.Center,
    ) {
        Text("SpendWise", style = MaterialTheme.typography.displaySmall, color = MaterialTheme.colorScheme.primary)
        Text(
            if (isRegister) "Create your account" else "Welcome back",
            style = MaterialTheme.typography.titleMedium,
            modifier = Modifier.padding(top = 4.dp, bottom = 24.dp),
        )
        OutlinedTextField(
            value = state.email, onValueChange = onEmail, label = { Text("Email") }, singleLine = true,
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Email),
            modifier = Modifier.fillMaxWidth().testTag("email"),
        )
        OutlinedTextField(
            value = state.password, onValueChange = onPassword, label = { Text("Password") }, singleLine = true,
            visualTransformation = PasswordVisualTransformation(),
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
            modifier = Modifier.fillMaxWidth().padding(top = 12.dp).testTag("password"),
        )
        if (state.error != null) {
            Text(state.error, color = MaterialTheme.colorScheme.error, modifier = Modifier.padding(top = 8.dp).testTag("error"))
        }
        Button(onClick = onSubmit, enabled = !state.loading, modifier = Modifier.fillMaxWidth().padding(top = 16.dp).height(48.dp).testTag("submit")) {
            if (state.loading) CircularProgressIndicator(Modifier.size(20.dp), strokeWidth = 2.dp)
            else Text(if (isRegister) "Create account" else "Sign in")
        }
        OutlinedButton(onClick = onGoogle, enabled = !state.loading, modifier = Modifier.fillMaxWidth().padding(top = 8.dp)) {
            Text("Continue with Google")
        }
        TextButton(onClick = onSwitch, modifier = Modifier.align(Alignment.CenterHorizontally).padding(top = 8.dp)) {
            Text(if (isRegister) "Already have an account? Sign in" else "New here? Create an account")
        }
    }
}

@Composable
fun AuthScreen(isRegister: Boolean, onSwitch: () -> Unit, vm: AuthViewModel = hiltViewModel()) {
    val state by vm.state.collectAsStateWithLifecycle()
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    AuthForm(
        isRegister = isRegister,
        state = state,
        onEmail = vm::onEmail,
        onPassword = vm::onPassword,
        onSubmit = { vm.submit(isRegister) },
        onGoogle = {
            scope.launch {
                // default_web_client_id is generated by the google-services plugin from google-services.json.
                when (val r = requestGoogleIdToken(context, context.getString(R.string.default_web_client_id))) {
                    is AppResult.Success -> vm.onGoogleToken(r.value)
                    is AppResult.Failure -> vm.onError(r.error.message)
                }
            }
        },
        onSwitch = onSwitch,
    )
}
